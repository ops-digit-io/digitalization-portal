const DICT: Record<Locale, Strings> = { en: EN, de: DE, zh: ZH, fr: FR, es: ES, sr: SR, hu: HU, ro: RO, pt: PT, sk: SK };

/** Translate a key for a locale; falls back to English, then to `fallback`, then the key. */
export function translate(locale: Locale, key: string, fallback?: string): string {
  return DICT[locale]?.[key] ?? DICT.en[key] ?? fallback ?? key;
}

/** The full set of keys every locale must define — English is the source of truth. */
export function localeKeys(): string[] {
  return Object.keys(EN);
}

