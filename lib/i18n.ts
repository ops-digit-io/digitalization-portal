/**
 * Interface i18n. English is the default and the authoritative key set; every other
 * locale carries a COMPLETE translation of that set — enforced by `i18n.test.ts`,
 * which fails if any locale is missing (or has an extra) key. That is what makes the
 * "100% translated" claim a checked fact rather than an aspiration.
 *
 * The localizable surface is the app chrome: the tagline and header controls, the
 * launchpad category names, and every tile's title/subtitle. Page bodies and external
 * content (department markdown, the spec docs) are data, not chrome, and are not keyed
 * here. Adding a locale is one entry in `LOCALES` plus one full dictionary in `DICT`;
 * adding a tile is one key in every dictionary (the test names any it misses).
 *
 * Keys resolve against the active locale, then fall back to English, then to the
 * caller's `fallback`, then to the key itself.
 */

